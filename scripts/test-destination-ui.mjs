import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,channel:'msedge'});
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(()=>localStorage.setItem('idr-onboarded','true'));
try {
  await page.goto('http://127.0.0.1:5173',{waitUntil:'domcontentloaded',timeout:60000});
  const opener=page.getByRole('button',{name:'Search destination',exact:true});
  await opener.waitFor();
  await page.waitForTimeout(7000);
  assert.equal(await page.getByText('GO BEYOND THE SIGNAL',{exact:true}).count(),0);
  await page.screenshot({path:'artifacts/destination-home-browser.png'});
  await opener.click();
  await page.getByRole('button',{name:'Motorcycle / scooter',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Motorcycle / scooter',exact:true}).getAttribute('aria-pressed'),'true');
  await page.getByRole('button',{name:'Car',exact:true}).click();
  const start=page.getByRole('combobox',{name:'Starting point'}),end=page.getByRole('combobox',{name:'Destination',exact:true});
  assert.equal(await start.inputValue(),'Your current location');
  await end.fill('Indore');
  await page.getByRole('option').filter({has:page.getByText('Indore',{exact:true})}).first().click();
  assert.equal(await end.inputValue(),'Indore');
  await start.fill('Bhopal');
  await page.getByRole('option').filter({has:page.getByText('Bhopal',{exact:true})}).first().click();
  assert.equal(await start.inputValue(),'Bhopal');
  await page.getByRole('button',{name:'Swap starting point and destination'}).click();
  assert.equal(await start.inputValue(),'Indore');assert.equal(await end.inputValue(),'Bhopal');
  await page.screenshot({path:'artifacts/destination-search-browser.png'});
  await end.fill('zzzznotaplacezzzz');
  await page.getByText('No places found.',{exact:false}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Get directions',exact:true}).isDisabled(),true);
  await page.getByRole('button',{name:'Close destination search'}).click();
  assert.equal(await page.locator('dialog').count(),0);
  await opener.click();await page.keyboard.press('Escape');
  assert.equal(await page.locator('dialog').count(),0);
  assert.equal(await page.locator('.mobile-nav button').count(),3);
  await page.locator('.mobile-nav').getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('button',{name:'Light',exact:true}).click();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
  await page.screenshot({path:'artifacts/qa-1.5/settings-light.png',fullPage:true});
  await page.getByRole('button',{name:'Dark',exact:true}).click();
  await page.locator('.mobile-nav').getByRole('button',{name:'My drives',exact:true}).click();
  await page.getByText('Your next drive starts here.',{exact:true}).waitFor();
  await page.locator('.mobile-nav').getByRole('button',{name:'Navigate',exact:true}).click();
  await opener.waitFor();
  assert.deepEqual(errors,[]);
  console.log('PASS: hero replacement, open, both real offline autocomplete fields, swap, vehicle mode, invalid text, cancel, Escape, settings themes, drive list and return to map, no JS errors. Android road confirmation is tested on device separately.');
} finally {await browser.close();}
